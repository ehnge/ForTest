import { writeFile } from 'node:fs/promises';
import { generateSyntheticData } from '../src/data/synthetic.ts';

const dataset = generateSyntheticData();
// Generated entirely from local synthetic fixtures. No credentials are read here.
const quote = value => typeof value === 'string' ? "'" + value.replaceAll("'", "''") + "'" : String(value);
let sql = '-- Generated by npm run seed:generate. Synthetic data only; default seed 42.\nbegin;\n';
for (const [table, rows] of [
  ['sample_people', dataset.people], ['health_observations', dataset.observations], ['demo_events', dataset.events],
]) {
  const columns = Object.keys(rows[0]);
  for (let i = 0; i < rows.length; i += 500) {
    sql += `insert into public.${table} (${columns.join(',')}) values\n`;
    sql += rows.slice(i, i + 500).map(row => '(' + columns.map(c => quote(row[c])).join(',') + ')').join(',\n');
    sql += '\non conflict (id) do nothing;\n';
  }
}
sql += 'commit;\n';
await writeFile(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`Generated ${dataset.people.length} travelers, ${dataset.observations.length} observations, ${dataset.events.length} events.`);
